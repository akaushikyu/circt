#!/usr/bin/env python3
"""Design catalogue for the hls-est validation harness.

Every HLSFactory design harvested into
<Test/HLS>/hlsfactory/Inputs/<suite>/<design>/ has a generated lit test
<Test/HLS>/hlsfactory/<suite>/<suite>__<design>.test (see generate.py there)
whose header and RUN line record the top function, the mode the design
reached (full / check-only / errors / errors-check-only / xfail) and the exact
cgeist invocation (sources, -I dirs, -D defines, extra flags).  This module
turns those tests into one record per design so that run_hlsest.py and
run_vitis.py drive both tools from the same description.

Two extra datasets are added:
  polybench_pragmas  <Test/HLS>/polybench/*.c except hls-est-e2e.c (hand-written
                     pragma tests; top = --function= of their first RUN line)
  basic              <circt>/test/hls-est/Estimation/basic/*.mlir, which have
                     no C source (mode 'mlir-only')

Lit substitutions used by the RUN lines (tools/cgeist/Test/lit.cfg and
Test/HLS/lit.local.cfg):
  %stdinclude    -resource-dir=<clang resource dir> -I <Test>/polybench/utilities
  %vitis_include -I <Test/HLS>/Inputs/vitis       (Vitis header stand-ins)
The resource dir is not recorded here (it depends on the clang that built
cgeist: `clang -print-resource-dir`); the runner must add it.  The absolute
-I dirs the substitutions imply are recorded per design in 'lit_includes'.

Default catalogue (since 2026-10-13): catalog="v2" (load_designs) / --catalog v2
(this CLI, run_hlsest.py, run_vitis.py) reads the HLSFactory 1.1.0 tree itself
(common.DEFAULT_HLSFACTORY_ROOT = /mnt/d/HLSFactory_v2/HLSFactory, or
$HLSFACTORY_ROOT) through hlsfactory_v2.py: hlsfactory.toml / dataset_hls.tcl /
Tcl projects, evaluated by a small Tcl interpreter.  Designs keep the keys of
their Polygeist copies; one whose source set is identical to the copy's IS the
copy's record (so cache keys and results stay valid), others point at the
HLSFactory tree (field 'source_match' says which).  polybench_pragmas and basic
are added as in the Polygeist catalogue.  catalog="polygeist" / --catalog
polygeist (or HLS_EST_CATALOG=polygeist in the environment) selects the older
catalogue built from the Polygeist lit copies described above.

Held-out catalogue: catalog="heldout" / --catalog heldout reads the held-out evaluation designs
(hls-doc/heldout.md; common.DEFAULT_HELDOUT_ROOT = /mnt/d/HLS_heldout, or $HLS_HELDOUT_ROOT) from
<root>/catalog/<dataset>/<design>/hlsfactory.toml with the same rules, and nothing else (no
polybench_pragmas or basic).  Each record carries its frozen split ('eval' / 'locked', split.json);
heldout_select() refuses the locked split until Peter releases it.  catalog="heldout2" reads the second
held-out set (hls-doc/heldout2.md; /mnt/d/HLS_heldout2 or $HLS_HELDOUT2_ROOT) the same way; each set has its
own split and its own release variable (common.HELDOUT_SETS), and its records carry 'heldout_set'.

Python 3.10, stdlib only.  Paths are stored in WSL spelling ('dir') and in
Windows spelling ('win_dir'); the module runs from either side.
"""
from __future__ import annotations

import argparse
import json
import os
import posixpath
import re
import shlex
import sys
from collections import Counter
from pathlib import Path

DEFAULT_TEST_HLS_DIR = "/mnt/d/HLS/Polygeist/tools/cgeist/Test/HLS"
WSL_DISTRO = os.environ.get("WSL_DISTRO_NAME", "Ubuntu-22.04")

MODES = ("full", "check-only", "errors", "errors-check-only", "xfail", "skip",
         "mlir-only", "v2")     # v2: an HLSFactory_v2 design that is not its Polygeist copy
SRC_LANG = {".c": "c", ".cc": "cpp", ".cpp": "cpp", ".cxx": "cpp"}
# Flags every generated RUN line carries; they are not design-specific.
FIXED_FLAGS = {"-S", "--hls-annotate"}
LIT_SUBS = {"%stdinclude", "%vitis_include"}
QUOTES = "\"'"

HEADER_RE = re.compile(
    r"^# HLSFactory (?P<rel>.+?) \(top: (?P<top>[^)]*)\), generated by generate\.py\.$")
MODE_RE = re.compile(r"^# Mode: (?P<mode>[a-z-]+)\.$")
RUN_RE = re.compile(r"^# RUN: cd (?P<dir>.+?) && (?P<not>not )?cgeist (?P<cmd>.*)$")
INPUTS_PREFIX = "%S/../Inputs/"
REASON_PREFIXES = (
    "cgeist cannot generate code for this design, for reasons unrelated to HLS pragmas: ",
    "Reason: clang cannot parse the design with the Vitis stand-in headers: ",
    "Code generation fails independently of pragmas: ",
)
BOILERPLATE = {
    "Pragma parsing, placement and validation are checked instead.",
    "XFAIL: *",
}
FUNC_RE = re.compile(r"^\s*func\.func\s+(?P<private>private\s+)?@(?P<name>[A-Za-z_$.][\w$.]*)",
                     re.M)


class DesignParseError(Exception):
    """A .test file whose shape this parser does not understand."""


# --------------------------------------------------------------------------
# Paths: WSL ('/mnt/d/...', '/home/...') <-> Windows ('D:/...', '//wsl.localhost/...')
# --------------------------------------------------------------------------
def to_wsl(p: str) -> str:
    p = str(p).replace("\\", "/")
    m = re.match(r"^([A-Za-z]):/(.*)$", p)
    if m:
        return f"/mnt/{m[1].lower()}/{m[2]}"
    m = re.match(r"^//wsl(?:\.localhost|\$)/[^/]+/(.*)$", p)
    if m:
        return "/" + m[1]
    return p


def to_win(p: str) -> str:
    p = to_wsl(p)
    m = re.match(r"^/mnt/([a-z])/(.*)$", p)
    if m:
        return f"{m[1].upper()}:/{m[2]}"
    return f"//wsl.localhost/{WSL_DISTRO}{p}"


def local(p: str) -> Path:
    """The path as the machine running this script can open it."""
    return Path(to_win(p) if os.name == "nt" else to_wsl(p))


def lang_of(src: str) -> str:
    return SRC_LANG.get(posixpath.splitext(src)[1].lower(), "unknown")


def slug(name: str) -> str:
    """Benchmark name made safe for file and project names (one design,
    'Monte-Carlo__Random 100 Paths', has spaces)."""
    return re.sub(r"[^\w.+-]+", "_", name)


# --------------------------------------------------------------------------
# cgeist command-line tokens
# --------------------------------------------------------------------------
def parse_cgeist_tokens(toks: list[str], sources_first: bool) -> dict:
    """Split the tokens after 'cgeist' into sources / --function / -I / -D /
    -o / lit substitutions / everything else.  Stops at the shell redirection
    or pipe that follows the command."""
    sources: list[str] = []
    i = 0
    if sources_first:
        while i < len(toks) and not toks[i].startswith("--function"):
            sources.append(toks[i])
            i += 1
        if i == len(toks):
            raise DesignParseError("no --function argument")
    function_arg = None
    includes: list[str] = []
    defines: list[str] = []
    extra: list[str] = []
    lit_subs: list[str] = []
    out = None
    while i < len(toks):
        t = toks[i]
        i += 1
        if t in ("2>&1", "|", ">", "<", "&&", ";"):
            break
        if t.startswith("--function="):
            function_arg = t.split("=", 1)[1]
        elif t == "--function":
            function_arg = toks[i]
            i += 1
        elif t in FIXED_FLAGS:
            continue
        elif t in LIT_SUBS:
            lit_subs.append(t)
        elif t == "-I":
            includes.append(toks[i])
            i += 1
        elif t.startswith("-I"):
            includes.append(t[2:])
        elif t == "-D":
            defines.append(toks[i])
            i += 1
        elif t.startswith("-D"):
            defines.append(t[2:])
        elif t == "-o" and i < len(toks) and toks[i] == "%t.mlir":
            # The lit-only MLIR output (what %hlsfactory_mlir expands to); a test whose
            # name has whitespace spells it out quoted (Polygeist 33982ef0, O129).
            i += 1
        elif t == "-o":
            out = toks[i]
            i += 1
        elif t.startswith("-o") and len(t) > 2:
            out = t[2:]
        elif t == "%s":
            sources.append("%s")
        else:
            extra.append(t)
    if function_arg is None:
        raise DesignParseError("no --function argument")
    return {"sources": sources, "function_arg": function_arg,
            "includes": includes, "defines": defines, "cgeist_args": extra,
            "lit_subs": lit_subs, "out": out}


def lit_includes_for(lit_subs: list[str], test_hls_wsl: str) -> list[str]:
    """Absolute -I dirs that the lit substitutions in a RUN line expand to."""
    test_dir = posixpath.normpath(posixpath.join(test_hls_wsl, ".."))
    out = []
    for s in lit_subs:
        if s == "%stdinclude":
            out.append(posixpath.join(test_dir, "polybench", "utilities"))
        elif s == "%vitis_include":
            out.append(posixpath.join(test_hls_wsl, "Inputs", "vitis"))
    return out


# --------------------------------------------------------------------------
# HLSFactory .test files
# --------------------------------------------------------------------------
def safe_name(rel: str) -> str:
    """Design path -> test-file stem, exactly as generate.py does it."""
    return rel.replace("/", "__").replace(" ", "_")


def parse_hlsfactory_test(test_file: Path, suite: str, test_hls_wsl: str) -> dict:
    lines = test_file.read_text(encoding="utf-8", errors="replace").splitlines()
    header = None
    mode = None
    run = None
    reason_lines: list[str] = []
    for ln in lines:
        if header is None:
            m = HEADER_RE.match(ln)
            if not m:
                raise DesignParseError(f"first line is not the HLSFactory header: {ln!r}")
            header = m
            continue
        if mode is None:
            m = MODE_RE.match(ln)
            if not m:
                raise DesignParseError(f"second line is not '# Mode: ...': {ln!r}")
            mode = m["mode"]
            if mode not in MODES:
                raise DesignParseError(f"unknown mode {mode!r}")
            continue
        if ln.startswith("# RUN:"):
            if run is not None:
                raise DesignParseError("more than one RUN line")
            run = ln
            continue
        if run is None and ln.startswith("#"):
            reason_lines.append(ln[1:].strip())
    if header is None or mode is None:
        raise DesignParseError("missing header or mode line")
    if run is None:
        raise DesignParseError("no RUN line")

    m = RUN_RE.match(run)
    if not m:
        raise DesignParseError(f"RUN line has an unexpected shape: {run!r}")
    cd = m["dir"].strip()
    if len(cd) >= 2 and cd[0] == cd[-1] and cd[0] in QUOTES:
        cd = cd[1:-1]
    if not cd.startswith(INPUTS_PREFIX):
        raise DesignParseError(f"RUN line does not cd into Inputs/: {cd!r}")
    rel = header["rel"]
    if cd[len(INPUTS_PREFIX):] != rel:
        raise DesignParseError(f"header design {rel!r} != RUN dir {cd!r}")
    stem = test_file.stem
    # Older generate.py output kept spaces in the stem ('Random 100 Paths').
    if stem not in (safe_name(rel), rel.replace("/", "__")):
        raise DesignParseError(f"test stem {stem!r} != safe_name({rel!r})")
    if rel == suite:
        # The suite root itself is a design (hp_fft_hls: an aggregate Tcl at
        # the root names every variant's FFT.cpp); there is no 'suite__' prefix.
        benchmark = stem
    elif rel.startswith(suite + "/"):
        benchmark = stem[len(suite) + 2:]
    else:
        raise DesignParseError(f"design {rel!r} is not under suite {suite!r}")

    try:
        toks = shlex.split(m["cmd"])
    except ValueError as e:
        raise DesignParseError(f"cannot tokenize RUN line: {e}") from e
    cmd = parse_cgeist_tokens(toks, sources_first=True)
    if not cmd["sources"]:
        raise DesignParseError("no source files before --function")
    if cmd["out"] != "/dev/null":
        raise DesignParseError(f"unexpected -o {cmd['out']!r}")

    reasons = []
    for r in reason_lines:
        if r in BOILERPLATE or not r:
            continue
        for p in REASON_PREFIXES:
            if r.startswith(p):
                r = r[len(p):]
                break
        reasons.append(r)

    d_wsl = posixpath.join(test_hls_wsl, "hlsfactory", "Inputs", rel)
    return {
        "dataset": suite,
        "benchmark": benchmark,
        "slug": slug(benchmark),
        "top": header["top"],
        "mode": mode,
        "reason": "; ".join(reasons),
        "dir": d_wsl,
        "win_dir": to_win(d_wsl),
        "sources": cmd["sources"],
        "includes": cmd["includes"],
        "defines": cmd["defines"],
        "cgeist_args": cmd["cgeist_args"],
        "function_arg": cmd["function_arg"],
        "expect_nonzero_exit": bool(m["not"]),
        "lit_includes": lit_includes_for(cmd["lit_subs"], test_hls_wsl),
        "test_file": to_wsl(str(test_file)),
        "lang": lang_of(cmd["sources"][0]),
    }


def load_hlsfactory(test_hls_wsl: str, problems: list[str]) -> list[dict]:
    hlsf = local(posixpath.join(test_hls_wsl, "hlsfactory"))
    designs = []
    for suite_dir in sorted(p for p in hlsf.iterdir() if p.is_dir()):
        suite = suite_dir.name
        if suite == "Inputs":
            continue
        for tf in sorted(suite_dir.glob("*.test")):
            try:
                designs.append(parse_hlsfactory_test(tf, suite, test_hls_wsl))
            except DesignParseError as e:
                problems.append(f"{to_wsl(str(tf))}: {e}")
    return designs


# --------------------------------------------------------------------------
# polybench pragma tests (Test/HLS/polybench/*.c)
# --------------------------------------------------------------------------
POLY_RUN_RE = re.compile(r"^//\s*RUN:\s*cgeist\s+(?P<cmd>.*)$")


def load_polybench_pragmas(test_hls_wsl: str, problems: list[str]) -> list[dict]:
    pdir_wsl = posixpath.join(test_hls_wsl, "polybench")
    pdir = local(pdir_wsl)
    designs = []
    for c in sorted(pdir.glob("*.c")):
        if c.name == "hls-est-e2e.c":
            continue
        text = c.read_text(encoding="utf-8", errors="replace")
        run = None
        for ln in text.splitlines():
            m = POLY_RUN_RE.match(ln)
            if m and "--function=" in ln:
                run = m
                break
        if run is None:
            problems.append(f"{to_wsl(str(c))}: no '// RUN: cgeist ... --function=' line")
            continue
        try:
            cmd = parse_cgeist_tokens(shlex.split(run["cmd"]), sources_first=False)
        except (DesignParseError, ValueError) as e:
            problems.append(f"{to_wsl(str(c))}: {e}")
            continue
        sources = [c.name if s == "%s" else s for s in cmd["sources"]] or [c.name]
        lit_inc = lit_includes_for(cmd["lit_subs"], test_hls_wsl)
        designs.append({
            "dataset": "polybench_pragmas",
            "benchmark": c.stem,
            "slug": slug(c.stem),
            "top": cmd["function_arg"],
            "mode": "full",
            "reason": "",
            "dir": pdir_wsl,
            "win_dir": to_win(pdir_wsl),
            "sources": sources,
            "includes": cmd["includes"] + [d for d in lit_inc if d.endswith("/utilities")],
            "defines": cmd["defines"],
            "cgeist_args": cmd["cgeist_args"],
            "function_arg": cmd["function_arg"],
            "expect_nonzero_exit": False,
            "lit_includes": lit_inc,
            "test_file": to_wsl(str(c)),
            "lang": lang_of(sources[0]),
        })
    return designs


# --------------------------------------------------------------------------
# basic (.mlir only)
# --------------------------------------------------------------------------
def load_basic(circt_wsl: str, problems: list[str]) -> list[dict]:
    bdir_wsl = posixpath.join(circt_wsl, "test", "hls-est", "Estimation", "basic")
    bdir = local(bdir_wsl)
    designs = []
    if not bdir.is_dir():
        problems.append(f"{bdir_wsl}: basic MLIR directory not found")
        return designs
    for f in sorted(bdir.glob("*.mlir")):
        text = f.read_text(encoding="utf-8", errors="replace")
        funcs = [m["name"] for m in FUNC_RE.finditer(text) if not m["private"]]
        if len(funcs) == 1:
            top = funcs[0]
        elif "kernel" in funcs:
            top = "kernel"
        else:
            problems.append(f"{to_wsl(str(f))}: cannot pick a top among func.func {funcs}")
            continue
        mlir_wsl = posixpath.join(bdir_wsl, f.name)
        designs.append({
            "dataset": "basic",
            "benchmark": f.stem,
            "slug": slug(f.stem),
            "top": top,
            "mode": "mlir-only",
            "reason": "no C source; hand-written MLIR input",
            "dir": bdir_wsl,
            "win_dir": to_win(bdir_wsl),
            "sources": [f.name],
            "includes": [],
            "defines": [],
            "cgeist_args": [],
            "function_arg": top,
            "expect_nonzero_exit": False,
            "lit_includes": [],
            "test_file": mlir_wsl,
            "mlir": mlir_wsl,
            "lang": "mlir",
        })
    return designs


# --------------------------------------------------------------------------
# HLSFactory v2: the HLSFactory 1.1.0 tree itself (opt-in; hlsfactory_v2.py)
# --------------------------------------------------------------------------
CATALOGS = ("polygeist", "v2", "heldout", "heldout2")
HELDOUT_CATALOGS = ("heldout", "heldout2")             # the keys of common.HELDOUT_SETS
HELDOUT_SPLITS = ("eval", "locked", "all")


def _common():
    """The harness's common.py (shared defaults), imported on first use."""
    here = str(Path(__file__).resolve().parent)
    if here not in sys.path:
        sys.path.insert(0, here)
    import common                            # noqa: E402  (harness module)
    return common


def hlsfactory_root() -> str:
    return to_wsl(os.environ.get("HLSFACTORY_ROOT") or _common().DEFAULT_HLSFACTORY_ROOT).rstrip("/")


def default_catalog() -> str:
    """'v2' (the HLSFactory 1.1.0 tree), unless HLS_EST_CATALOG names another catalogue."""
    catalog = os.environ.get("HLS_EST_CATALOG") or _common().DEFAULT_CATALOG
    if catalog not in CATALOGS:
        raise ValueError(f"HLS_EST_CATALOG={catalog!r} is not one of {', '.join(CATALOGS)}")
    return catalog


def load_hlsfactory_v2(root: str | None = None, test_hls_dir: str = DEFAULT_TEST_HLS_DIR,
                       problems: list[str] | None = None, info: dict | None = None) -> list[dict]:
    """One record per HLSFactory 1.1.0 design under <root>/hlsfactory/hls_dataset_sources (rules:
    hlsfactory_v2.py).  The records have this module's shape plus 'origin' ('hlsfactory_v2'), 'flows',
    'v2_dir' / 'v2_win_dir', 'source_match' and 'v2' (toml, Tcl facts, source comparison).  `info`
    receives {'skipped': [...], 'vanished': [...], 'root': root}: entries that are not designs, and
    Polygeist designs the tree no longer has."""
    here = str(Path(__file__).resolve().parent)
    if here not in sys.path:
        sys.path.insert(0, here)
    import hlsfactory_v2 as V2               # noqa: E402  (harness module)
    own = problems is None
    problems = [] if own else problems
    root_wsl = to_wsl(root).rstrip("/") if root else hlsfactory_root()
    test_hls_wsl = to_wsl(test_hls_dir).rstrip("/")
    V2.LOCAL = local if os.name == "nt" else None
    recs, rep = V2.load(root_wsl, load_hlsfactory(test_hls_wsl, problems), test_hls_wsl, problems,
                        to_win=to_win)
    if info is not None:
        info.update(rep)
    if own and problems:
        raise DesignParseError("\n".join(problems))
    return recs


# --------------------------------------------------------------------------
# held-out evaluation catalogue (hls-doc/heldout.md)
# --------------------------------------------------------------------------
def _heldout_set(name: str) -> dict:
    sets = _common().HELDOUT_SETS
    if name not in sets:
        raise ValueError(f"unknown held-out set {name!r} (one of {', '.join(sets)})")
    return sets[name]


def heldout_root(name: str = "heldout") -> str:
    s = _heldout_set(name)
    return to_wsl(os.environ.get(s["root_env"]) or s["default_root"]).rstrip("/")


def load_heldout_split(root: str | None = None, name: str = "heldout") -> dict:
    """<root>/split.json, checked against the committed copy (tools/hls-est-validate/<set>/split.json):
    the split was frozen before any result existed, so the two must be identical."""
    root = root or heldout_root(name)
    path = Path(local(posixpath.join(root, "split.json")))
    split = json.loads(path.read_text(encoding="utf-8"))
    copy = _heldout_set(name)["split_copy"]
    if not copy.is_file() or json.loads(copy.read_text(encoding="utf-8")) != split:
        raise DesignParseError(f"{path} differs from the committed copy {copy}: the held-out split is "
                               f"frozen ({_heldout_set(name)['doc']}); restore one from the other")
    return split


def load_heldout(root: str | None = None, problems: list[str] | None = None,
                 info: dict | None = None, name: str = "heldout") -> list[dict]:
    """One record per design of the held-out set `name` under <root>/catalog/<dataset>/<design>/hlsfactory.toml
    (the HLSFactory 1.1 layout; rules: hlsfactory_v2.discover).  Records have the v2 shape with origin
    `name` ('heldout' / 'heldout2'), mode 'heldout', 'heldout_set' = `name` and 'heldout' = {split, family}
    from split.json."""
    here = str(Path(__file__).resolve().parent)
    if here not in sys.path:
        sys.path.insert(0, here)
    import hlsfactory_v2 as V2               # noqa: E402  (harness module)
    own = problems is None
    problems = [] if own else problems
    root = to_wsl(root).rstrip("/") if root else heldout_root(name)
    V2.LOCAL = local if os.name == "nt" else None
    recs, skipped = V2.discover(root, problems, src_root=posixpath.join(root, "catalog"))
    split = load_heldout_split(root, name)
    assign = split["designs"]
    out = []
    for r in recs:
        key = f"{r['dataset']}/{r['benchmark']}"
        r.update(origin=name, mode="heldout", win_dir=to_win(r["dir"]), v2_win_dir=to_win(r["dir"]))
        if name != "heldout":
            r["heldout_set"] = name
        if key not in assign:
            problems.append(f"{key}: held-out design without a split entry (split.json)")
            continue
        r["heldout"] = dict(assign[key])
        out.append(r)
    missing = set(assign) - {f"{r['dataset']}/{r['benchmark']}" for r in out}
    for key in sorted(missing):
        problems.append(f"{key}: in split.json but not in the catalogue")
    if info is not None:
        info.update({"skipped": skipped, "root": root, "split_seed": split.get("seed")})
    if own and problems:
        raise DesignParseError("\n".join(problems))
    return out


def heldout_set_of(d: dict) -> str:
    """The held-out set of a held-out design record ('heldout' for the records of the first set)."""
    return d.get("heldout_set") or "heldout"


def heldout_locked_released(name: str = "heldout") -> bool:
    s = _heldout_set(name)
    return os.environ.get(s["release_env"]) == s["release_value"]


def heldout_select(designs: list[dict], split: str = "eval", name: str | None = None) -> list[dict]:
    """The held-out designs of `split` ('eval', 'locked' or 'all'; other records pass through).  The
    'locked' designs are refused (SystemExit) until Peter releases them (hls-doc/heldout.md, heldout2.md),
    per set: the sets of the held-out records in `designs`, and `name` when given (with no records and no
    `name`: the first set).  Every tool that runs hls-est on held-out designs or scores them calls this first."""
    if split not in HELDOUT_SPLITS:
        raise ValueError(f"held-out split {split!r} is not one of {', '.join(HELDOUT_SPLITS)}")
    sets = {heldout_set_of(d) for d in designs if "heldout" in d} | ({name} if name else set())
    if split != "eval":
        for s in sorted(sets or {"heldout"}):
            if not heldout_locked_released(s):
                hs = _heldout_set(s)
                raise SystemExit(f"the {s!r} 'locked' split is not released ({hs['doc']}); Peter releases "
                                 f"it by setting {hs['release_env']}={hs['release_value']}")
    return [d for d in designs
            if "heldout" not in d or split == "all" or d["heldout"]["split"] == split]


def heldout_visible(designs: list[dict]) -> list[dict]:
    """`designs` without the locked held-out designs of every set that is not released (for tools that list or
    digest designs without choosing a split, e.g. run_hlsest.select_designs under HLS_EST_CATALOG=heldout2)."""
    return [d for d in designs if not ("heldout" in d and d["heldout"]["split"] == "locked"
                                      and not heldout_locked_released(heldout_set_of(d)))]


def heldout_refuse_locked_key(key_or_path: str):
    """SystemExit when `key_or_path` names a locked design of an unreleased held-out set: a results key
    '<dataset>/<benchmark>', or a path under a Vitis cache directory .../vitis-cache/<dataset>/<benchmark>/...
    (align_arrays.py, vitis_trace.py, rtl_memories.py read reports and RTL of one design by key or path)."""
    c = _common()
    s = str(key_or_path).replace("\\", "/")
    parts = s.split("/")
    key = None
    if "vitis-cache" in parts and len(parts) > parts.index("vitis-cache") + 2:
        i = parts.index("vitis-cache")
        key = f"{parts[i + 1]}/{parts[i + 2]}"
    elif not s.startswith("/") and s.count("/") >= 1:
        key = s
    name = c.heldout_set_of_key(key) if key else None
    if name is None or heldout_locked_released(name):
        return
    if key in heldout_locked_keys(name=name):
        hs = _heldout_set(name)
        raise SystemExit(f"{key}: a locked design of the held-out set {name!r} ({hs['doc']}); it is not inspected "
                         f"until Peter releases it ({hs['release_env']})")


def heldout_locked_keys(root: str | None = None, name: str = "heldout") -> set[str]:
    """Keys of the locked held-out designs (for filtering result files without loading the catalogue)."""
    split = load_heldout_split(root, name)
    return {k for k, v in split["designs"].items() if v["split"] == "locked"}


