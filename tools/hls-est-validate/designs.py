def default_circt_dir() -> str:
    # <circt>/tools/hls-est-validate/designs.py
    return to_wsl(str(Path(__file__).resolve().parents[2]))


def verify_design(d: dict) -> list[str]:
    """Check that the files the record names exist on disk."""
    errs = []
    ddir = local(d["dir"])
    if not ddir.is_dir():
        return [f"{d['dataset']}/{d['benchmark']}: dir missing: {d['dir']}"]
    for s in d["sources"]:
        if not (ddir / s).is_file():
            errs.append(f"{d['dataset']}/{d['benchmark']}: source missing: {s}")
    for inc in d["includes"] + d["lit_includes"]:
        p = local(inc) if posixpath.isabs(inc) else ddir / inc
        if not p.is_dir():
            errs.append(f"{d['dataset']}/{d['benchmark']}: include dir missing: {inc}")
    return errs


def load_designs(test_hls_dir: str = DEFAULT_TEST_HLS_DIR,
                 circt_dir: str | None = None,
                 datasets: list[str] | None = None,
                 modes: list[str] | None = None,
                 verify: bool = True,
                 problems: list[str] | None = None,
                 catalog: str | None = None,
                 hlsfactory_root_dir: str | None = None,
                 info: dict | None = None) -> list[dict]:
    """All designs as dicts (see module docstring).  Parse/verification
    problems are appended to `problems` (or raised if it is None).
    catalog: 'polygeist' (the HLSFactory designs from the Polygeist lit copies),
    'v2' (load_hlsfactory_v2) or 'heldout' (load_heldout: the held-out designs only, every split;
    scoring tools narrow it with heldout_select); None = default_catalog()."""
    own = problems is None
    problems = [] if own else problems
    test_hls_wsl = to_wsl(test_hls_dir).rstrip("/")
    circt_wsl = to_wsl(circt_dir).rstrip("/") if circt_dir else default_circt_dir()
    catalog = catalog or default_catalog()
    if catalog in HELDOUT_CATALOGS:
        designs = load_heldout(problems=problems, info=info, name=catalog)
        if datasets:
            designs = [d for d in designs if d["dataset"] in set(datasets)]
        if verify:
            for d in designs:
                problems.extend(verify_design(d))
        if own and problems:
            raise DesignParseError("\n".join(problems))
        return designs
    if catalog == "v2":
        hlsf = load_hlsfactory_v2(hlsfactory_root_dir, test_hls_wsl, problems, info)
    elif catalog == "polygeist":
        hlsf = load_hlsfactory(test_hls_wsl, problems)
    else:
        raise ValueError(f"unknown catalog {catalog!r} (one of {', '.join(CATALOGS)})")
    designs = (hlsf
               + load_polybench_pragmas(test_hls_wsl, problems)
               + load_basic(circt_wsl, problems))
    if datasets:
        want = set(datasets)
        designs = [d for d in designs if d["dataset"] in want]
    if modes:
        want = set(modes)
        designs = [d for d in designs if d["mode"] in want]
    if verify:
        for d in designs:
            problems.extend(verify_design(d))
    if own and problems:
        raise DesignParseError("\n".join(problems))
    return designs


def count_table(designs: list[dict]) -> str:
    per: dict[str, Counter] = {}
    for d in designs:
        per.setdefault(d["dataset"], Counter())[d["mode"]] += 1
    total: Counter = Counter()
    for c in per.values():
        total.update(c)
    cols = [m for m in MODES if total[m]] + sorted(m for m in total if m not in MODES)
    w = max([len("dataset"), len("TOTAL")] + [len(k) for k in per])
    head = f"{'dataset':<{w}}  {'total':>5}  " + "  ".join(f"{c:>{max(len(c), 5)}}" for c in cols)
    rows = [head, "-" * len(head)]
    for ds in sorted(per):
        c = per[ds]
        rows.append(f"{ds:<{w}}  {sum(c.values()):>5}  "
                    + "  ".join(f"{c[m]:>{max(len(m), 5)}}" for m in cols))
    rows.append("-" * len(head))
    rows.append(f"{'TOTAL':<{w}}  {sum(total.values()):>5}  "
                + "  ".join(f"{total[m]:>{max(len(m), 5)}}" for m in cols))
    return "\n".join(rows)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--test-hls-dir", default=DEFAULT_TEST_HLS_DIR,
                    help="Polygeist tools/cgeist/Test/HLS (WSL or Windows spelling)")
    ap.add_argument("--circt-dir", default=None,
                    help="CIRCT tree holding test/hls-est/Estimation/basic "
                         "(default: derived from this file's location)")
    ap.add_argument("--out", default=None, help="write the design list as JSON here")
    ap.add_argument("--datasets", default=None,
                    help="comma-separated dataset (suite) names to keep")
    ap.add_argument("--modes", default=None,
                    help="comma-separated modes to keep: " + ",".join(MODES))
    ap.add_argument("--no-verify", action="store_true",
                    help="do not check that sources/include dirs exist on disk")
    ap.add_argument("--list", action="store_true",
                    help="also print one line per design")
    ap.add_argument("--catalog", choices=CATALOGS, default=None,
                    help="HLSFactory designs from the HLSFactory 1.1.0 tree ('v2', the default), from "
                         "the Polygeist lit copies ('polygeist'), or the held-out evaluation catalogue "
                         "('heldout', hls-doc/heldout.md; 'heldout2', hls-doc/heldout2.md); $HLS_EST_CATALOG changes "
                         "the default")
    ap.add_argument("--hlsfactory-root", default=None,
                    help=f"HLSFactory tree for --catalog v2 (default $HLSFACTORY_ROOT or "
                         f"{_common().DEFAULT_HLSFACTORY_ROOT})")
    a = ap.parse_args(argv)
    problems: list[str] = []
    info: dict = {}
    catalog = a.catalog or default_catalog()
    designs = load_designs(
        a.test_hls_dir, a.circt_dir,
        datasets=a.datasets.split(",") if a.datasets else None,
        modes=a.modes.split(",") if a.modes else None,
        verify=not a.no_verify, problems=problems, catalog=catalog,
        hlsfactory_root_dir=a.hlsfactory_root, info=info)
    if catalog == "v2":
        print(f"catalog: v2 ({info.get('root')})")
    print(count_table(designs))
    if catalog == "v2":
        import hlsfactory_v2 as V2           # noqa: E402  (imported by load_hlsfactory_v2)
        print("\nsource match against the Polygeist copies (HLSFactory designs):")
        print(V2.catalogue_report([d for d in designs if d.get("origin") == "hlsfactory_v2"], info))
    multi = sum(1 for d in designs if len(d["sources"]) > 1)
    langs = Counter(d["lang"] for d in designs)
    print(f"\ndesigns: {len(designs)}; with >1 source: {multi}; "
          "lang: " + ", ".join(f"{k}={v}" for k, v in sorted(langs.items())))
    if a.list:
        for d in designs:
            print(f"{d['dataset']}/{d['benchmark']}  top={d['top']}  mode={d['mode']}  "
                  f"sources={' '.join(d['sources'])}")
    if a.out:
        with open(a.out, "w", encoding="utf-8") as fh:
            json.dump(designs, fh, indent=1)
        print(f"wrote {len(designs)} designs to {a.out}")
    if problems:
        print(f"\n{len(problems)} problem(s):", file=sys.stderr)
        for p in problems:
            print("  " + p, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
