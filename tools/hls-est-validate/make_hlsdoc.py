#!/usr/bin/env python3
"""Render the generated pages of the hls-doc (~/circt/hls-doc/) from harness results.

    python3 make_hlsdoc.py [--vitis results/vitis.json] [--hlsest <run_hlsest.py result json>]
                           [--out-dir ../../hls-doc] [--pages ground-truth,memories,results]

Pages (every number is copied from the JSON inputs; the harness configuration is quoted from
common.py and labelled as such):
  hls-doc/ground-truth.md           the Vitis ground truth: run configuration, per-dataset counts,
                                    one row per design (status, BRAM/DSP/FF/LUT with utilisation %,
                                    top, csynth time), and the excluded designs with the reason
                                    (make_sheet.exclusion, the rule the workbook uses); with an hls-est
                                    run (--hlsest, or when results.md is rendered too), also the run's
                                    designs that have no ground-truth entry at all (unsynthesised)
  hls-doc/ground-truth-memories.md  every memory row of every design (module, array, instance,
                                    core, bound port type, words, bits, banks, BRAM)
  hls-doc/results.md                one hls-est run against the ground truth: per-dataset summary
                                    (compared / exact / |err|), one row per design, the mismatches
                                    by |diff| with the largest array differences (compare.compare_one),
                                    and the run configuration (hls-est git hash, shim, pipeline,
                                    cgeist md5)

--hlsest defaults to results/hlsest.json when it exists, else to the newest *.json under
~/hls-est-work/*/runs/ whose recorded pipeline (`_meta.pipeline`) contains common.DEFAULT_PIPELINE.
The page says which file was used and whether its pipeline and shim are the current harness
defaults, so a stale default file is visible rather than silent.

Every generated page starts with the line
    generated by tools/hls-est-validate/make_hlsdoc.py from <inputs> on <date>
(the hls-doc convention for generated pages; hand-written pages carry no such line).
Python 3 stdlib plus what make_sheet.py imports (openpyxl).
"""
import argparse
import glob
import os
import sys
import time
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common as C  # noqa: E402
from compare import compare_one, summarize  # noqa: E402
from make_sheet import exclusion  # noqa: E402

SCRIPT = "tools/hls-est-validate/make_hlsdoc.py"
DOC_DIR = C.CIRCT / "hls-doc"
RUNS_GLOB = str(Path.home() / "hls-est-work" / "*" / "runs" / "*.json")
PAGES = ("ground-truth", "memories", "results")
TOTAL_KEYS = ("BRAM", "DSP", "FF", "LUT", "BRAM_util_pct", "DSP_util_pct", "FF_util_pct", "LUT_util_pct")
LARGEST_ARRAYS = 4          # array differences listed per mismatch
EXCERPT = 160               # characters of an error text shown in a table cell


# ------------------------------------------------------------------ Markdown --

def md_cell(value):
    """One table cell: '' for None, numbers as printed by Python, text with '|' and newlines escaped."""
    if value is None:
        return ""
    if isinstance(value, float):
        return f"{value:g}"
    return str(value).replace("|", "\\|").replace("\n", " ")


def md_table(header, rows):
    """A GitHub-flavoured Markdown table (header, separator, one line per row)."""
    lines = ["| " + " | ".join(md_cell(h) for h in header) + " |",
             "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(md_cell(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def short_path(path):
    """A path as the notes spell it: repo-relative inside ~/circt, '~/...' under $HOME."""
    p = Path(path).resolve()
    try:
        return str(p.relative_to(C.CIRCT))
    except ValueError:
        pass
    try:
        return "~/" + str(p.relative_to(Path.home()))
    except ValueError:
        return str(p)


def generated_line(inputs, date):
    return f"generated by {SCRIPT} from {' and '.join(inputs)} on {date}"


def distinct(values):
    """The distinct non-empty values, comma separated (for per-design fields that should agree)."""
    vals = sorted({str(v) for v in values if v not in (None, "")})
    return ", ".join(vals) if vals else "(not recorded)"


def first_line(text, limit=EXCERPT):
    text = (text or "").strip()
    return text.splitlines()[0][:limit] if text else ""


# ------------------------------------------------------------------- inputs --

def vitis_ok(v):
    return bool(v) and v.get("status") == "ok"


def load_vitis(path):
    """{design key: record} from results/vitis.json (it has no _meta entry; drop one if present)."""
    data = C.load_json(path, {}) or {}
    return {k: v for k, v in data.items() if k != "_meta"}


def load_hlsest(path):
    """({design key: record}, _meta) from a run_hlsest.py result file."""
    data = C.load_json(path, {}) or {}
    meta = data.pop("_meta", {}) or {}
    return data, meta


def newest_default_pipeline_run():
    """The newest run_hlsest.py result under ~/hls-est-work/*/runs/ whose _meta.pipeline contains
    common.DEFAULT_PIPELINE, or None. compare.py outputs (*.cmp.json) are skipped; a file is
    parsed only when its first bytes mention _meta (dump_json sorts keys, so _meta comes first)."""
    candidates = []
    for p in glob.glob(RUNS_GLOB):
        if p.endswith(".cmp.json"):
            continue
        try:
            with open(p, errors="replace") as f:
                head = f.read(4096)
        except OSError:
            continue
        if '"_meta"' not in head:
            continue
        meta = (C.load_json(p, {}) or {}).get("_meta") or {}
        if C.DEFAULT_PIPELINE in (meta.get("pipeline") or ""):
            candidates.append((os.path.getmtime(p), p))
    return Path(max(candidates)[1]) if candidates else None


def pick_hlsest(given):
    """(path, how it was chosen) for the hls-est run results.md renders."""
    if given:
        return Path(given), "given with --hlsest"
    default = C.RESULTS_DIR / "hlsest.json"
    if default.exists():
        return default, "the default, results/hlsest.json"
    newest = newest_default_pipeline_run()
    if newest:
        return newest, ("results/hlsest.json does not exist: the newest run under ~/hls-est-work/*/runs/ "
                        "whose recorded pipeline contains the harness default pipeline")
    sys.exit("make_hlsdoc.py: no hls-est run JSON found (results/hlsest.json is missing and no run under "
             "~/hls-est-work/*/runs/ used the default pipeline); give --hlsest <file>")


# ------------------------------------------------------------- ground truth --

def per_dataset_counts(V):
    """One row per dataset: designs, with a result, excluded, BRAM sum, memory rows, loop rows."""
    by = defaultdict(list)
    for key, v in V.items():
        by[key.split("/", 1)[0]].append(v)
    rows = []
    for ds, vs in sorted(by.items()):
        ok = [v for v in vs if vitis_ok(v)]
        rows.append([ds, len(vs), len(ok), len(vs) - len(ok),
                     sum((v.get("totals") or {}).get("BRAM") or 0 for v in ok),
                     sum(len(v.get("memories") or []) for v in ok),
                     sum(len(v.get("loops") or []) for v in ok)])
    rows.append(["all", sum(r[1] for r in rows), sum(r[2] for r in rows), sum(r[3] for r in rows),
                 sum(r[4] for r in rows), sum(r[5] for r in rows), sum(r[6] for r in rows)])
    return rows


def design_rows(V):
    rows = []
    for key in sorted(V):
        v = V[key]
        ds, bm = key.split("/", 1)
        totals = (v.get("totals") or {}) if vitis_ok(v) else {}
        rows.append([ds, bm, v.get("status"), *[totals.get(k) for k in TOTAL_KEYS], v.get("top"),
                     v.get("elapsed_s")])
    return rows


def excluded_rows(V):
    rows = []
    for key in sorted(V):
        v = V[key]
        if vitis_ok(v):
            continue
        category, reason = exclusion(v)
        rows.append([*key.split("/", 1), v.get("status"), category, reason, first_line(v.get("note"))])
    return rows


def never_run_rows(V, catalogue_keys):
    """The catalogue designs (the keys of a run over the whole catalogue) that have no entry in the ground
    truth at all: Vitis was never started on them, so they are in neither table above."""
    rows = []
    for key in sorted(set(catalogue_keys) - set(V)):
        category, reason = exclusion(None)
        rows.append([*key.split("/", 1), category, reason])
    return rows


def render_ground_truth(V, vitis_path, date, catalogue_keys=None, catalogue_source=""):
    ok = [v for v in V.values() if vitis_ok(v)]
    config = [
        ["source file", short_path(vitis_path)],
        ["Vitis version (recorded per design)", distinct(v.get("vitis_version") for v in V.values())],
        ["part (recorded per design)", distinct(v.get("part") for v in V.values())],
        ["clock (recorded per design)", distinct(v.get("clock") for v in V.values())],
        ["flow_target (harness configuration, common.FLOW_TARGET)", C.FLOW_TARGET],
        ["syn.array_partition.throughput_driven",
         "off: the ground-truth setting (run_vitis.py --td off, common.EXTRA_HLS_CFG = "
         f"{'; '.join(C.EXTRA_HLS_CFG)}); the td=auto result set is results/vitis-tdauto.json"],
        ["Vitis install (harness configuration)", f"{C.VITIS_WIN_ROOT} (Windows), run from WSL through cmd.exe"],
        ["designs / with a result / excluded", f"{len(V)} / {len(ok)} / {len(V) - len(ok)}"],
        ["memory rows / loop rows (designs with a result)",
         f"{sum(len(v.get('memories') or []) for v in ok)} / {sum(len(v.get('loops') or []) for v in ok)}"],
        ["cached artifacts per design",
         f"{short_path(C.CACHE_ROOT)}/<dataset>/<benchmark>/<hash>/ (report/, log/, db/)"],
    ]
    parts = [
        generated_line([short_path(vitis_path)], date), "",
        "# Vitis ground truth", "",
        "Every number on this page is copied from the harness result file named in the first line, which "
        "`run_vitis.py` writes from the parsed `csynth.xml` / `*_csynth.rpt` of each design (totals and "
        "utilisation percentages come from `csynth.xml`). A design without a Vitis result is listed under "
        "[Excluded designs](#excluded-designs) with the reason and takes part in no comparison.", "",
        "## Run configuration", "", md_table(["setting", "value"], config), "",
        "## Per dataset", "",
        md_table(["dataset", "designs", "with a result", "excluded", "BRAM_18K (sum)", "memory rows", "loop rows"],
                 per_dataset_counts(V)), "",
        "## Designs", "",
        "Utilisation columns are percentages of the part (`xc7z020clg400-1`). `csynth time` is the wall-clock "
        "time of the `v++ -c --mode hls` run in seconds (a cached design keeps the time of its original run).", "",
        md_table(["dataset", "benchmark", "status", "BRAM_18K", "DSP", "FF", "LUT", "BRAM %", "DSP %", "FF %",
                  "LUT %", "top", "csynth time (s)"], design_rows(V)), "",
        "## Excluded designs", "",
        "The category and reason come from `make_sheet.exclusion` (the rule the workbook's "
        "\"excluded designs\" sheet uses), derived from the Vitis status and error text only.", "",
        md_table(["dataset", "benchmark", "Vitis status", "category", "why it is excluded", "Vitis error (first line)"],
                 excluded_rows(V)), "",
    ]
    if catalogue_keys is not None:
        never = never_run_rows(V, catalogue_keys)
        parts += [
            f"## Unsynthesised designs ({len(never)})", "",
            f"Designs of the harness catalogue (the designs of the hls-est run `{catalogue_source}`) that "
            "have no entry in the ground-truth file: Vitis was never run on them, so they have no ground "
            "truth and take part in no comparison. Together with the failed and timed-out designs above "
            "they are every catalogue design without ground truth. The reasons are recorded in "
            "`tools/hls-est-validate/MEMOS.md`: the hlsyn-vitis runner was stopped by decision #52 (its remaining "
            "designs exceed the time and memory budget, and their kernels are covered by polybench and "
            "machsuite); the `basic` designs are MLIR inputs without C sources.", "",
            md_table(["dataset", "benchmark", "category", "why it has no ground truth"], never), "",
        ]
    return "\n".join(parts)


# ----------------------------------------------------------- memory rows ----

MEMORY_HEADER = ["design", "module", "array", "instance", "bank", "core", "bound port type", "words", "bits",
                 "banks", "BRAM_18K"]


def memory_rows(key, mems):
    return [[key, m.get("module"), m.get("array"), m.get("Memory"), m.get("bank"), m.get("core"), m.get("optype"),
             m.get("Words"), m.get("Bits"), m.get("Banks"), m.get("bram")] for m in mems]


def render_memories(V, vitis_path, date):
    designs = [(k, v.get("memories") or []) for k, v in sorted(V.items()) if vitis_ok(v)]
    total_rows = sum(len(m) for _, m in designs)
    parts = [
        generated_line([short_path(vitis_path)], date), "",
        "# Vitis ground truth: memory rows", "",
        f"{total_rows} memory rows over {sum(1 for _, m in designs if m)} designs "
        f"({len(designs)} designs with a Vitis result). One row per `* Memory:` table entry of every "
        "`*_csynth.rpt` of the design, as `vitis_parse.py` records it:", "",
        "- `module`: the RTL module whose report lists the memory (the top, a `*_Pipeline_*` module or a callee).",
        "- `array`: the C array the instance belongs to; partition banks `<array>_<k>_U` are grouped under their "
        "array with the bank index in `bank` (`vitis_parse.group_banks`, confirmed against the bind nodes).",
        "- `instance`: the memory instance name of the report (`<array>_U`, `<array>_<k>_U`).",
        "- `core`: the storage core Vitis bound (`RAM_1P`, `RAM_2P`, `RAM_T2P`, `RAM_S2P`, `RAM_1WNR`, `ROM_1P`, "
        "`RAM_AUTO_*`, ...).",
        "- `bound port type`: the OPTYPE of the design's bind node (`ram_1p`, `ram_2p`, `ram_t2p`, `ram_s2p`, "
        "`rom_1p`, ...); empty when the memory has no bind node (library ROMs, adapters).",
        "- `words`, `bits`, `banks`, `BRAM_18K`: the table's own columns (`BRAM_18K` is the number this harness "
        "sums per array).", "",
    ]
    for key, mems in designs:
        bram = sum(m.get("bram") or 0 for m in mems)
        parts += [f"## {key}", "", f"{len(mems)} rows, BRAM_18K sum {bram}", ""]
        if mems:
            parts += [md_table(MEMORY_HEADER, memory_rows(key, mems)), ""]
    return "\n".join(parts)


# ---------------------------------------------------------------- results ----

def run_configuration(meta, hlsest_path, how, H):
    """The run-configuration rows of results.md, from the run's _meta (what run_hlsest.py recorded)."""
    pipeline = meta.get("pipeline") or ""
    shim = Path(meta.get("shim") or "").name
    n_ok = sum(1 for r in H.values() if r.get("status") == "ok")
    return [
        ["run file", f"{short_path(hlsest_path)} ({how})"],
        ["run id", meta.get("run_id")],
        ["pipeline (as recorded)", pipeline],
        ["pipeline is the current harness default (common.DEFAULT_PIPELINE)",
         "yes" if pipeline == C.DEFAULT_PIPELINE else f"no; the current default is: {C.DEFAULT_PIPELINE}"],
        ["top selection", meta.get("top_passes")],
        ["shim", f"{shim}" + ("" if shim == C.DEFAULT_SHIM else f" (the current harness default is {C.DEFAULT_SHIM})")],
        ["hls-est git hash", meta.get("hls_est_git")],
        ["hls-est binary / sha256", f"{meta.get('hls_est')} / {meta.get('hls_est_sha256')}"],
        ["cgeist binary / md5", f"{meta.get('cgeist')} / {meta.get('cgeist_md5') or 'not recorded'}"],
        ["Polygeist HEAD at the run", meta.get("polygeist_head") or "not recorded"],
        ["MLIR reused from", meta.get("mlir_from") or "(cgeist was run or its cache used)"],
        ["hls-est timeout (s)", meta.get("timeout")],
        ["designs in the run / hls-est ok", f"{len(H)} / {n_ok}"],
    ]


def dataset_summary_rows(summary):
    rows = []
    for ds, d in sorted(summary["per_dataset"].items()):
        rows.append([ds, d["designs"], d["compared"], d["exact"], d["abs_error"], d["hlsest_failed"],
                     d["vitis_failed"]])
    rows.append(["all", summary["designs"], summary["compared"], summary["exact"], summary["total_abs_error"],
                 summary["hlsest_missing"], summary["vitis_missing"]])
    return rows


def array_differences(row, limit=LARGEST_ARRAYS):
    """'name: hls-est vs Vitis' for the arrays with the largest |diff| of one compared design."""
    arrays = sorted((a for a in row.get("arrays", []) if a.get("diff")), key=lambda a: -abs(a["diff"]))

    def side(bram):
        return "-" if bram is None else str(bram)     # '-': the array does not exist on that side

    return "; ".join(f"{a['name']}: {side(a['hlsest_bram'])} vs {side(a['vitis_bram'])}" for a in arrays[:limit])


def mismatch_rows(rows):
    out = []
    for r in sorted(rows, key=lambda r: -abs(r.get("diff") or 0)):
        if r["status"] == "compared" and not r["exact"]:
            out.append([r["dataset"], r["benchmark"], r["vitis_bram"], r["hlsest_bram"], f"{r['diff']:+d}",
                        array_differences(r)])
    return out


def design_status(r, v):
    if r["status"] == "compared":
        return "exact" if r["exact"] else "mismatch"
    if r["status"] == "vitis missing":
        return f"no ground truth: excluded ({exclusion(v)[0]})"
    if r["status"] == "sources differ":
        return "ground truth is for other sources: excluded (compare.py `sources differ`)"
    return r["hlsest_status"]            # the hls-est failure text (CLAUDE.md status strings)


def design_result_rows(rows, V):
    out = []
    for r in sorted(rows, key=lambda r: r["key"]):
        diff = f"{r['diff']:+d}" if r.get("diff") is not None else None
        out.append([r["dataset"], r["benchmark"], r["vitis_bram"], r["hlsest_bram"], diff,
                    design_status(r, V.get(r["key"]))])
    return out


def not_in_run(V, H):
    """Designs with a Vitis result that the run did not cover, counted per dataset."""
    missing = defaultdict(int)
    for key, v in V.items():
        if key not in H and vitis_ok(v):
            missing[key.split("/", 1)[0]] += 1
    return ", ".join(f"{ds} {n}" for ds, n in sorted(missing.items()))


def render_results(V, H, meta, hlsest_path, how, vitis_path, date):
    rows = [compare_one(k, V.get(k), H.get(k)) for k in sorted(H)]
    summary = summarize(rows)
    mismatches = mismatch_rows(rows)
    parts = [
        generated_line([short_path(vitis_path), short_path(hlsest_path)], date), "",
        "# hls-est results against the Vitis ground truth", "",
        "Every number is copied from the two result files named in the first line, joined by "
        "`compare.compare_one` (the same comparison the workbook and `compare.py` print). `diff` is "
        "hls-est minus Vitis; a design is exact when the totals are equal. Per-array differences come from "
        "the run's `--bram-debug-json` files (arrays matched by C variable name).", "",
        "## Run", "", md_table(["setting", "value"], run_configuration(meta, hlsest_path, how, H)), "",
        "## Summary per dataset", "",
        "`compared` counts the designs with both a Vitis total and an hls-est total; `|err|` is the sum of "
        "|diff| over them; `hls-est failed` are cgeist / hls-est failures and timeouts; `no ground truth` are "
        "the excluded designs.", "",
        md_table(["dataset", "designs in run", "compared", "exact", "|err|", "hls-est failed", "no ground truth"],
                 dataset_summary_rows(summary)), "",
    ]
    absent = not_in_run(V, H)
    if absent:
        parts += [f"Designs with a Vitis result that this run did not cover (per dataset): {absent}.", ""]
    parts += [
        f"## Mismatches ({len(mismatches)}), largest |diff| first", "",
        "The last column lists up to "
        f"{LARGEST_ARRAYS} arrays with the largest per-array difference as `array: hls-est vs Vitis`; `-` means "
        "the array does not exist on that side (Vitis deleted or renamed it, or hls-est did not see it) and "
        "counts as 0 in the difference.", "",
        md_table(["dataset", "benchmark", "Vitis BRAM", "hls-est BRAM", "diff", "largest array differences"],
                 mismatches), "",
        "## All designs of the run", "",
        md_table(["dataset", "benchmark", "Vitis BRAM", "hls-est BRAM", "diff", "status"],
                 design_result_rows(rows, V)), "",
    ]
    return "\n".join(parts)


# ------------------------------------------------------------------- main ----

def write_page(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {short_path(path)} ({path.stat().st_size} bytes)")


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--vitis", default=str(C.RESULTS_DIR / "vitis.json"), help="ground truth (run_vitis.py)")
    ap.add_argument("--hlsest", default=None,
                    help="run_hlsest.py result file (default: results/hlsest.json, else the newest run under "
                         "~/hls-est-work/*/runs/ that used the default pipeline)")
    ap.add_argument("--out-dir", default=str(DOC_DIR), help="the hls-doc directory")
    ap.add_argument("--pages", default=",".join(PAGES), help=f"comma list of {', '.join(PAGES)}")
    args = ap.parse_args()

    pages = [p.strip() for p in args.pages.split(",") if p.strip()]
    unknown = [p for p in pages if p not in PAGES]
    if unknown:
        sys.exit(f"make_hlsdoc.py: unknown page(s) {', '.join(unknown)}; choose from {', '.join(PAGES)}")
    out_dir = Path(args.out_dir)
    date = time.strftime("%Y-%m-%d")
    V = load_vitis(args.vitis)
    if not V:
        sys.exit(f"make_hlsdoc.py: no designs in {args.vitis}")

    if "ground-truth" in pages:
        # The catalogue is read from the hls-est run (a full run covers every catalogue design), so the
        # page can list the designs Vitis never ran without loading the catalogue itself.
        catalogue_keys, catalogue_source = None, ""
        if args.hlsest or "results" in pages:
            run_path, _ = pick_hlsest(args.hlsest)
            catalogue_keys, catalogue_source = list(load_hlsest(run_path)[0]), short_path(run_path)
        write_page(out_dir / "ground-truth.md",
                   render_ground_truth(V, args.vitis, date, catalogue_keys, catalogue_source))
    if "memories" in pages:
        write_page(out_dir / "ground-truth-memories.md", render_memories(V, args.vitis, date))
    if "results" in pages:
        hlsest_path, how = pick_hlsest(args.hlsest)
        H, meta = load_hlsest(hlsest_path)
        if not H:
            sys.exit(f"make_hlsdoc.py: no designs in {hlsest_path}")
        if (meta.get("pipeline") or "") != C.DEFAULT_PIPELINE:
            print(f"note: {short_path(hlsest_path)} did not use the current default pipeline "
                  "(the page says so in its Run table)")
        write_page(out_dir / "results.md", render_results(V, H, meta, hlsest_path, how, args.vitis, date))


if __name__ == "__main__":
    main()
