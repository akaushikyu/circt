#!/usr/bin/env python3
"""Generate hls-doc/configuration.md from hls-est's own description of its configuration.

Input: `hls-est --dump-config-schema` (every key: path, type, unit, range, default, description,
the assumptions-inventory rows it exposes and the passes that read it) and `hls-est --list-plugins`
(the registered implementations of every plugin interface). The page is generated, never edited by
hand: change the schema table (lib/Dialect/Resource/Config/Schema.cpp) or the compiled-in defaults
(lib/Dialect/Resource/Config/data/) and re-run

  tools/hls-est-validate/make_config_doc.py [--hls-est build/clion/bin/hls-est] [--out hls-doc/configuration.md]
  tools/hls-est-validate/make_config_doc.py --check     # exit 1 when the page is stale

The default values come from the schema dump (which reads them from the compiled-in device and profile),
so the page, the loader's validation, --dump-default-config and this page cannot drift apart.
"""
import argparse
import datetime
import json
import re
import subprocess
import sys
from pathlib import Path

CIRCT = Path(__file__).resolve().parents[2]
DEFAULT_BIN = CIRCT / "build/clion/bin/hls-est"
DEFAULT_OUT = CIRCT / "hls-doc/configuration.md"
MAX_DEFAULT = 60  # characters of a default value shown inline

SECTIONS = [
    ("version", "Format version"),
    ("run", "run: device, tool profile, clock"),
    ("device", "device: the silicon (data-sheet facts, no tool policy)"),
    ("tool", "tool: the HLS tool profile (policies and the back end)"),
    ("frontend", "frontend: what the cgeist input encodes"),
    ("scheduling", "scheduling: the schedule model and its plugins"),
    ("plugins", "plugins: free-form sections of external plugins"),
]

INTRO = """\
# The hls-est configuration file

<!-- Generated by tools/hls-est-validate/make_config_doc.py from `hls-est --dump-config-schema` and
`hls-est --list-plugins` ({binary}) on {date}. Do not edit: change lib/Dialect/Resource/Config/Schema.cpp or the
compiled-in defaults under lib/Dialect/Resource/Config/data/, then re-run the script. -->

Every architectural assumption of hls-est that is data is a key of one JSON document (design memo
[design/configuration-and-plugins.md](design/configuration-and-plugins.md); the assumptions it exposes are
rows of [design/assumptions-inventory.md](design/assumptions-inventory.md)). What cannot be data is a
plugin interface ([plugins.md](plugins.md)); the keys of kind *plugin* below select an implementation.

**Defaults.** Without a file hls-est runs with the compiled-in device `amd-xc7z020clg400-1` and tool
profile `vitis-2025.1`, which reproduce the pre-configuration behaviour byte for byte (Peter decides any
default change; proposals go to `hls-doc/notes/MEMOS.md`).

**Precedence** (lowest first): the compiled-in base; the device and profile `run.device` / `run.tool`
name; each `--hls-config=<file>` in command-line order; each `--config-set <key.path>=<value>`; a pass
option given on the command line (for example `--auto-pipeline-unroll=pipeline-loops=32` beats
`tool.hls.options.pipeline_loops`).

**Commands.**

| Command | Prints |
|---|---|
| `--dump-default-config` | the compiled-in document, with every key's description |
| `--dump-effective-config` | the document after every file and `--config-set`, each changed key with a `_source` naming who set it, and the document hash (`_hash`, recorded by the harness) |
| `--dump-config-schema` | the table below as JSON (the input of this page) |
| `--default-pipeline` | runs `tool.pipeline` (the default pass pipeline of the profile); a pass flag given as well is an error |
| `--load-plugin=<lib>` / `--list-plugins` | loads a plugin library / lists every registered implementation |

**Validation.** Unknown keys, wrong types, values out of range, unknown enum values and unregistered
plugin names are errors that name the key and the file or `--config-set` that set it; keys that start
with `_` are comments. Cross-key checks refuse a priced port configuration no device memory has, a
`plugins.<name>` section no plugin key selects, and a reserved value that is not implemented
(`flatten_across_calls=true`); `calyx-fixed` refuses an `operator_latencies` class it does not read.
After the document is complete every selected plugin checks the device
(`checkDevice`): the Vitis memory mappers, for example, refuse a device without the RAMB18 model they
were measured on.

**Types.** *uint* is a non-negative integer, *resource vector* an object `{class: count}` over
`device.resource_classes[].name` (counts are integers or `"n/d"` strings), *port sets* arrays of arrays of
`r` / `w` / `rw`, *plugin* the name of a registered implementation of the interface in brackets. A path
`a[].b` is the key `b` of every element of the array `a`.

"""


DATE_RE = re.compile(r"\) on (\d{4}-\d{2}-\d{2})\. Do not edit")


def run(binary, *args):
    p = subprocess.run([str(binary), *args], capture_output=True, text=True)
    out = p.stdout if p.stdout.strip() else p.stderr
    if p.returncode != 0:
        sys.exit(f"{binary} {' '.join(args)} failed ({p.returncode}):\n{p.stderr[:2000]}")
    return out


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def fmt_default(key):
    if "default" not in key:
        return ""
    v = json.dumps(key["default"], separators=(", ", ": "), sort_keys=True)
    if len(v) > MAX_DEFAULT:
        return "*(see `--dump-default-config`)*"
    return f"`{cell(v)}`"


def fmt_type(key):
    t = key["type"]
    if key.get("interface"):
        t = f"plugin [`{key['interface']}`]"
    elif key.get("values"):
        t = f"{t}: `{cell(key['values'])}`"
    rng = []
    if "min" in key:
        rng.append(f">= {key['min']:g}")
    if "max" in key:
        rng.append(f"<= {key['max']:g}")
    if rng:
        t += " (" + ", ".join(rng) + ")"
    if key.get("optional"):
        t += ", optional"
    return cell(t)


def section_of(path):
    return path.split(".")[0].split("[")[0]


def subsection_of(path):
    parts = path.split(".")
    if parts[0] in ("tool", "scheduling", "device") and len(parts) > 2:
        return ".".join(parts[:2]).replace("[]", "")
    return None


def parse_plugins(text):
    interfaces, cur = {}, None
    for line in text.splitlines():
        if not line.strip():
            continue
        if not line.startswith(" ") and line.rstrip().endswith(":"):
            cur = line.strip()[:-1]
            interfaces[cur] = []
        elif cur is not None:
            name, _, rest = line.strip().partition(" ")
            origin, _, desc = rest.partition("] ")
            interfaces[cur].append((name, origin.lstrip("["), desc))
    return interfaces


def generate(binary, date):
    schema = json.loads(run(binary, "--dump-config-schema"))
    plugins = parse_plugins(run(binary, "--list-plugins"))
    out = [INTRO.replace("{binary}", Path(binary).name).replace("{date}", date)]
    out.append(f"Schema version {schema['version']}; {len(schema['keys'])} keys.\n")
    out.append("## Contents\n")
    for sec, title in SECTIONS:
        out.append(f"- [{title}](#{sec})")
    out.append("- [Registered plugins](#registered-plugins)\n")
    keys = schema["keys"]
    for sec, title in SECTIONS:
        rows = [k for k in keys if section_of(k["path"]) == sec]
        if not rows:
            continue
        out.append(f'<a id="{sec}"></a>\n\n## {title}\n')
        current_sub = None
        header = ("| Key | Type | Unit | Default | Description | Inventory rows | Read by |\n"
                  "|---|---|---|---|---|---|---|")
        out.append(header)
        for k in rows:
            sub = subsection_of(k["path"])
            if sub != current_sub and sub is not None:
                current_sub = sub
                out.append(f"\n**`{sub}`**\n\n{header}")
            out.append("| `{}` | {} | {} | {} | {} | {} | {} |".format(
                cell(k["path"]), fmt_type(k), cell(k.get("unit", "")), fmt_default(k),
                cell(k.get("doc", "")), cell(k.get("rows", "")), cell(k.get("readers", ""))))
        out.append("")
    out.append('<a id="registered-plugins"></a>\n\n## Registered plugins\n')
    out.append("The implementations compiled into hls-est (`--list-plugins`); a plugin library loaded with "
               "`--load-plugin` adds its own. The interfaces are described in [plugins.md](plugins.md).\n")
    out.append("| Interface | Implementation | Description |\n|---|---|---|")
    for iface in schema["plugin_interfaces"]:
        for name, origin, desc in plugins.get(iface, []):
            out.append(f"| `{iface}` | `{name}` | {cell(desc)} |")
    out.append("")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--hls-est", default=str(DEFAULT_BIN))
    ap.add_argument("--out", default=str(DEFAULT_OUT))
    ap.add_argument("--check", action="store_true", help="exit 1 when --out differs from the generated page")
    a = ap.parse_args()
    out = Path(a.out)
    if a.check:
        # The generation date of the page on disk is not a difference.
        old = out.read_text() if out.exists() else ""
        m = DATE_RE.search(old)
        text = generate(a.hls_est, m.group(1) if m else "")
        if old != text:
            print(f"{out} is stale: re-run {Path(__file__).name}", file=sys.stderr)
            return 1
        return 0
    text = generate(a.hls_est, datetime.date.today().isoformat())
    out.write_text(text)
    print(f"wrote {out} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
