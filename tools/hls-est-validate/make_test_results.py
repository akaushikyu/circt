#!/usr/bin/env python3
"""Render the hls-est test results into hls-doc/test-results/ (CMake target hls-est-results).

    python3 make_test_results.py [--hls-est <binary>] [-j 4] [--out-dir ../../hls-doc/test-results]

Runs every test of the Mirror suite (test/hls-est/Mirror, generated by mirror_cgeist_tests.py) the
way its RUN line does, with the given hls-est binary, and writes one Markdown page per dataset plus
a summary (README.md). Each row: test case -> hls-est prediction -> Vitis BRAM -> status.

Status of a row:
  exact        prediction == Vitis
  in band      Vitis < prediction <= 1.15 x Vitis (Peter's goal of 2026-10-10: exact, or an
               over-count of at most 15 %)
  over         prediction > 1.15 x Vitis
  under        prediction < Vitis
  no ground truth / top not found / hls-est failed / cgeist failure   (not compared)

The Vitis number is read from results/vitis.json (Vitis 2025.1 csynth, td=off) and used only when
that entry was synthesised from the sources the test compiles (the cache key the manifest records).
A row whose prediction differs from the test's pinned CHECK total is marked: the binary then no
longer gives the output the suite expects.
"""
import argparse
import concurrent.futures as cf
import datetime
import json
import re
import shlex
import subprocess
import sys
import time
from collections import Counter, OrderedDict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common as C                       # noqa: E402
import run_hlsest as RH                  # noqa: E402

MIRROR = C.CIRCT / "test" / "hls-est" / "Mirror"
MANIFEST = MIRROR / "manifest.json"
BAND_OVER = 0.15
FEATURE_GROUP = "cgeist-feature-tests"
STATUS_ORDER = ("exact", "in band", "over", "under", "no ground truth", "top not found", "hls-est failed",
                "cgeist failure")


def run_command(test_file, hls_est):
    """The hls-est command of a Mirror test's RUN line (FileCheck dropped), and its timeout or None."""
    text = Path(test_file).read_text(errors="replace")
    m = re.search(r"^// RUN: (.*)$", text, flags=re.M)
    run = m.group(1).split(" | FileCheck")[0]
    run = run.replace("%hls_est_math_costs", str(RH.DEFAULT_MATH_COSTS)).replace("%s", str(test_file))
    toks = shlex.split(run)
    timeout = None
    if toks[0] == "timeout":
        timeout = int(toks[1])
        toks = toks[2:]
    # An XFAIL-by-error test runs hls-est under the generator's memory cap (mirror_cgeist_tests.py
    # run_line(capped=True)); predict() applies the same cap through C.mem_limited.
    if toks[0] == "prlimit":
        toks = toks[toks.index("--") + 1:]
    assert toks[0] == "hls-est", toks[:3]
    pin = re.search(r"^// CHECK: Total BRAM: (\d+)\{\{\$\}\}$", text, flags=re.M)
    return [hls_est] + toks[1:], timeout, (int(pin.group(1)) if pin else None)


def predict(test_file, hls_est, default_timeout):
    cmd, timeout, pin = run_command(test_file, hls_est)
    t0 = time.time()
    try:
        p = subprocess.run(C.mem_limited(cmd), capture_output=True, text=True, errors="replace",
                           timeout=timeout or default_timeout)
    except subprocess.TimeoutExpired:
        return {"status": f"timeout {timeout or default_timeout}s", "pin": pin, "s": time.time() - t0}
    total, _ = RH.parse_hlsest_output(p.stdout)
    st = "ok" if p.returncode == 0 and total is not None else f"exit {p.returncode}"
    return {"status": st, "bram": total if st == "ok" else None, "pin": pin, "s": time.time() - t0}


def band(vitis, est):
    if est == vitis:
        return "exact"
    if est > vitis:
        return "in band" if est <= vitis * (1 + BAND_OVER) else "over"
    return "under"


def group_of(r):
    return r["design"].split("/")[0] if r.get("design") else FEATURE_GROUP


def vitis_now(r, V):
    """The Vitis td=off BRAM of the test's design, when results/vitis.json still holds the entry the
    manifest recorded (same cache key); else None."""
    vit = r.get("vitis") or {}
    v = V.get(r.get("design") or "")
    if not v or v.get("status") != "ok" or vit.get("key") != v.get("key") or vit.get("status") != "ok":
        return None
    return v["totals"]["BRAM"]


def row_of(r, V, pred):
    vb = vitis_now(r, V)
    row = {"test": r["test"], "mirror": r.get("mirror"), "design": r.get("design"), "top": r.get("top"),
           "vitis": vb, "pred": None, "pin": None, "note": ""}
    if r["outcome"] not in ("pass", "xfail"):
        row["status"] = "cgeist failure"
        row["note"] = r.get("reason", "")
        return row
    row["pin"] = pred["pin"]
    if pred["status"] != "ok":
        row["status"] = "hls-est failed"
        row["note"] = pred["status"] + (f"; {r['reason']}" if r.get("reason") else "")
        return row
    row["pred"] = pred["bram"]
    if r.get("design") and not r.get("top"):
        # cgeist emitted no function of the design's top: the test estimates every public function,
        # which is no estimate of the design (run_hlsest.py reports 'top not found')
        row["status"] = "top not found"
        row["note"] = "the design's top function is not in the MLIR; every public function is estimated"
        return row
    if pred["pin"] is not None and pred["pin"] != pred["bram"]:
        row["note"] = f"differs from the pinned CHECK ({pred['pin']})"
    if vb is None:
        row["status"] = "no ground truth"
        vit = r.get("vitis")
        if vit and vit.get("status") != "ok":
            row["note"] = (row["note"] + "; " if row["note"] else "") + vit["status"]
        return row
    row["status"] = band(vb, pred["bram"])
    return row


def md(s):
    return str("" if s is None else s).replace("|", "\\|").replace("\n", " ")


def flags_text(r):
    rl = r.get("run_line") or {}
    parts = [f"-I {i}" for i in rl.get("includes", [])] + [f"-D{d}" for d in rl.get("defines", [])]
    return " ".join(parts)


def counts(rows):
    c = Counter(r["status"] for r in rows)
    comp = [r for r in rows if r["status"] in ("exact", "in band", "over", "under")]
    err = sum(abs(r["pred"] - r["vitis"]) for r in comp)
    return c, len(comp), err


def generated_line(meta, hls_est, hls_md5, date):
    return (f"generated by tools/hls-est-validate/make_test_results.py from test/hls-est/Mirror "
            f"(manifest of {meta['date']}), hls-est {hls_est} (md5 {hls_md5}) and "
            f"tools/hls-est-validate/results/vitis.json on {date}")


def write_pages(out_dir, groups, manifest, rows_by_test, gen_line):
    out_dir.mkdir(parents=True, exist_ok=True)
    for old in out_dir.glob("*.md"):
        old.unlink()
    summary = [f"# hls-est test results", "", gen_line, "",
               "One row per cgeist HLS lit test (the Mirror suite, `test/hls-est/Mirror`; see "
               "[../tests.md](../tests.md)): the hls-est prediction with the default pipeline, the "
               "Vitis 2025.1 td=off BRAM_18K of the same sources, and the status: **exact**, **in band** "
               "(over-count of at most 15 %), **over** (more than 15 % over), **under**, or not compared "
               "(no ground truth, hls-est failed, or cgeist cannot compile the test, which then has no "
               "Mirror test).", "",
               "| dataset | tests | compared | exact | in band | over | under | no ground truth | "
               "top not found | hls-est failed | cgeist failure | exact + in band | sum \\|err\\| |",
               "|---|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|"]
    tot_rows = []
    for g, rows in groups.items():
        c, comp, err = counts(rows)
        tot_rows += rows
        good = c["exact"] + c["in band"]
        summary.append(f"| [{g}]({g}.md) | {len(rows)} | {comp} | {c['exact']} | {c['in band']} | {c['over']} | "
                       f"{c['under']} | {c['no ground truth']} | {c['top not found']} | {c['hls-est failed']} | "
                       f"{c['cgeist failure']} | {good} ({100 * good / comp:.0f} %) | {err} |" if comp else
                       f"| [{g}]({g}.md) | {len(rows)} | 0 | 0 | 0 | 0 | 0 | {c['no ground truth']} | "
                       f"{c['top not found']} | {c['hls-est failed']} | {c['cgeist failure']} | - | 0 |")
        page = [f"# hls-est test results: {g}", "", gen_line, "",
                f"[Summary](README.md). Status counts: " + ", ".join(f"{k} {c[k]}" for k in STATUS_ORDER if c[k]) + ".",
                "", "| test case | top | hls-est prediction | Vitis BRAM | status | note | cgeist flags of the RUN line |",
                "|---|---|--:|--:|---|---|---|"]
        for r in sorted(rows, key=lambda x: x["test"]):
            name = (f"[{r['test']}](../../{r['mirror']})" if r.get("mirror") else r["test"])
            mrec = rows_by_test[r["test"]]
            page.append(f"| {name} | {md(r['top'])} | {md(r['pred'])} | {md(r['vitis'])} | {r['status']} | "
                        f"{md(r['note'])} | {md(flags_text(mrec))} |")
        (out_dir / f"{g}.md").write_text("\n".join(page) + "\n")
    c, comp, err = counts(tot_rows)
    good = c["exact"] + c["in band"]
    summary.append(f"| **total** | **{len(tot_rows)}** | **{comp}** | **{c['exact']}** | **{c['in band']}** | "
                   f"**{c['over']}** | **{c['under']}** | **{c['no ground truth']}** | **{c['top not found']}** | "
                   f"**{c['hls-est failed']}** | "
                   f"**{c['cgeist failure']}** | **{good} ({100 * good / max(comp, 1):.0f} %)** | **{err}** |")
    differ = [r for r in tot_rows if r["note"].startswith("differs from the pinned")]
    summary += ["", f"Predictions that differ from the suite's pinned CHECK totals: {len(differ)}"
                + (" (" + ", ".join(r["test"] for r in differ[:20]) + ")" if differ else "") + ".",
                "", f"Pipeline (common.DEFAULT_PIPELINE when the suite was generated): `{manifest['_meta']['pipeline']}`."]
    (out_dir / "README.md").write_text("\n".join(summary) + "\n")
    return c, comp


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--hls-est", default=C.HLS_EST)
    ap.add_argument("-j", type=int, default=4)
    ap.add_argument("--timeout", type=int, default=600,
                    help="seconds per test whose RUN line sets no timeout")
    ap.add_argument("--out-dir", default=str(C.CIRCT / "hls-doc" / "test-results"))
    a = ap.parse_args()
    manifest = json.loads(MANIFEST.read_text())
    V = C.load_json(C.RESULTS_DIR / "vitis.json", {}) or {}
    tests = manifest["tests"]
    runnable = [r for r in tests if r["outcome"] in ("pass", "xfail")]
    t0 = time.time()
    with cf.ThreadPoolExecutor(a.j) as ex:
        preds = dict(zip((r["test"] for r in runnable),
                         ex.map(lambda r: predict(C.CIRCT / r["mirror"], a.hls_est, a.timeout), runnable)))
    rows = [row_of(r, V, preds.get(r["test"])) for r in tests]
    groups = OrderedDict()
    for r in sorted(rows, key=lambda r: (r["design"] is None, (r["design"] or "").split("/")[0], r["test"])):
        groups.setdefault(group_of(r), []).append(r)
    gen = generated_line(manifest["_meta"], a.hls_est, C.md5_of_file(a.hls_est), datetime.date.today().isoformat())
    c, comp = write_pages(Path(a.out_dir), groups, manifest, {r["test"]: r for r in tests}, gen)
    print(f"{len(rows)} tests, {comp} compared: " + ", ".join(f"{k} {c[k]}" for k in STATUS_ORDER if c[k])
          + f"; {round(time.time() - t0)} s; pages in {a.out_dir}")


if __name__ == "__main__":
    main()
