#!/usr/bin/env python3
"""Regenerate the git-derived appendices of hls-doc/notes/SESSION_LOG.md.

Everything above the line '## Appendix A' is hand-written and kept; the
appendices are rebuilt from `git log --name-status` of ~/circt (since the
snapshot commit e9da1aaf0) and of the Polygeist repo (since 90541e3b), plus
the current uncommitted state of both trees.

    python3 update_session_log.py
"""
import subprocess
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
CIRCT = HERE.parent.parent
# The notes moved into hls-doc/notes/ in phase P1b (2026-10-14); tools/hls-est-validate/SESSION_LOG.md
# is a one-line stub that says so.
LOG = CIRCT / "hls-doc" / "notes" / "SESSION_LOG.md"
POLY = Path("/mnt/d/HLS/Polygeist")
CIRCT_BASE, POLY_BASE = "e9da1aaf0", "90541e3b"


def git(repo, *args):
    return subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True).stdout


def commits(repo, base):
    out = []
    for block in git(repo, "log", "--reverse", "--format=@@%h %s", "--name-status", f"{base}..HEAD").split("@@")[1:]:
        lines = [l for l in block.splitlines() if l.strip()]
        out.append(f"### {lines[0]}\n")
        for l in lines[1:]:
            parts = l.split("\t")
            out.append(f"- {parts[0]} `{' -> '.join(parts[1:])}`")
        out.append("")
    return "\n".join(out)


def dirty(repo):
    rows = [l for l in git(repo, "status", "--short").splitlines() if not l.startswith("??") and l.strip() != "m llvm"
            and not l.endswith(" llvm")]
    return "\n".join(f"- `{l.strip()}`" for l in rows) or "- (clean)"


def main():
    text = LOG.read_text()
    head = text.split("## Appendix A")[0].rstrip() + "\n\n"
    stamp = time.strftime("%Y-%m-%d %H:%M")
    body = (
        "## Appendix A — every file changed in ~/circt (branch hls-est-vitis-match), per commit, oldest first\n\n"
        f"Generated by `update_session_log.py` at {stamp} from `git log --reverse --name-status {CIRCT_BASE}..HEAD` "
        f"({CIRCT_BASE} = snapshot of Peter's pre-existing uncommitted tree). A = added, M = modified, D = deleted. "
        "Large result JSONs are git-ignored.\n\n"
        + commits(CIRCT, CIRCT_BASE)
        + "\n## Appendix B — every file changed in Polygeist (/mnt/d/HLS, branch hls-est-vitis-match), per commit\n\n"
        + commits(POLY, POLY_BASE)
        + f"\n## Appendix C — uncommitted work at {stamp} (owned by running agents unless stated)\n\n"
        + "~/circt:\n\n" + dirty(CIRCT) + "\n\nPolygeist:\n\n" + dirty(POLY) + "\n"
    )
    LOG.write_text(head + body)
    print(f"rewrote {LOG} ({len((head + body).splitlines())} lines)")


if __name__ == "__main__":
    main()
