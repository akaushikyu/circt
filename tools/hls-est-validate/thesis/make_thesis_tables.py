def history(manifest, vitis, subset):
    hist = []
    for h in manifest["history"]:
        runs, meta = T.load_run(h["run"])
        rows = T.score(runs, vitis)
        s, sub = T.summarize(rows), T.summarize([r for r in rows if r["dataset"] in subset])
        cmp_path = Path(str(T.expand(h["run"]))[:-len(".json")] + ".cmp.json")
        recorded = json.load(open(cmp_path))["summary"] if cmp_path.exists() else None
        hist.append({**h, "summary": s, "subset": sub, "meta": meta,
                     "recorded": {"compared": recorded["compared"], "exact": recorded["exact"],
                                  "abs_err": recorded["total_abs_error"]} if recorded else None})
    return hist


