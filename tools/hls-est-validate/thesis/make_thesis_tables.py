def timing(csv_rows):
    pairs = []
    for r in csv_rows:
        h, v = r.get("hls-est time (s)"), r.get("Vitis csynth time (s)")
        if h and v:
            pairs.append((r["dataset"] + "/" + r["benchmark"], float(h), float(v)))
    hs = [p[1] for p in pairs]
    vs = [p[2] for p in pairs]
    # hls-est times are printed with one decimal: a 0.0 is below 0.05 s, so the ratio uses 0.05 s
    ratio = [v / max(h, 0.05) for _, h, v in pairs]
    q = lambda xs, f: sorted(xs)[min(len(xs) - 1, int(f * len(xs)))]
    return {"n": len(pairs), "pairs": pairs,
            "hlsest_median_s": statistics.median(hs), "hlsest_p90_s": q(hs, 0.9), "hlsest_max_s": max(hs),
            "hlsest_total_s": sum(hs),
            "vitis_median_s": statistics.median(vs), "vitis_p90_s": q(vs, 0.9), "vitis_max_s": max(vs),
            "vitis_total_s": sum(vs), "vitis_total_h": sum(vs) / 3600.0,
            "speedup_median": statistics.median(ratio), "speedup_p10": q(ratio, 0.1), "speedup_min": min(ratio),
            "speedup_total": sum(vs) / max(sum(hs), 0.05),
            "hlsest_under_1s": sum(h < 1.0 for h in hs), "hlsest_over_60s": sum(h > 60.0 for h in hs),
            "slower_than_vitis": sum(r < 1.0 for r in ratio)}


