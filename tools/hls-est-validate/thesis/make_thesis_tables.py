def ablation(manifest, vitis):
    ab = manifest["ablation"]
    ref_runs, _ = T.load_run(ab["reference"])
    ref = T.summarize(T.score(ref_runs, vitis))
    out = []
    for p in ab["passes"]:
        path = Path(T.expand(ab["dir"])) / f"{p}.json"
        runs, _ = T.load_run(path)
        s = T.summarize(T.score(runs, vitis))
        out.append({"pass": p, "summary": s, "d_exact": ref["exact"] - s["exact"],
                    "d_in_band": ref["in_band"] - s["in_band"], "abs_err_without": s["abs_err"]})
    return ref, out


