def render(template, numbers, tables):
    def sub(m):
        key = m.group(1)
        if key.startswith("table:"):
            return tables[key[6:]].markdown()
        if key not in numbers:
            raise KeyError(f"template placeholder {{{{{key}}}}} has no value in numbers.json")
        return str(numbers[key])
    return re.sub(r"\{\{([A-Za-z0-9_:.]+)\}\}", sub, template)


def flat_numbers(prefix, d, out, digits=1):
    for k, v in d.items():
        if isinstance(v, (int, float)) and not isinstance(v, bool):
            out[f"{prefix}{k}"] = fmt(v, digits) if isinstance(v, float) else fmt(v)
        elif v is None:
            out[f"{prefix}{k}"] = "–"


def device_capacity(path=T.CIRCT / "test" / "hls-est" / "Config" / "Inputs" / "default-config.json"):
    """BRAM_18K of the target part, from hls-est's default configuration dump (device.resource_classes)."""
