def out_of_band(rows, manifest):
    cls = manifest["outofband_classes"]
    per = json.load(open(T.expand(cls["per_design"])))["per"]
    desc = T.parse_class_table(T.expand(cls["class_table"]))
    oob = [r for r in rows if r["status"] == "compared" and r["band"] not in T.IN_BAND]
    groups = {}
    for r in oob:
        p = per.get(r["key"])
        if p and p.get("net"):
            dom = max(p["net"].items(), key=lambda kv: abs(kv[1]))[0]
        else:
            dom = "unclassified"
        g = groups.setdefault(dom, {"designs": [], "sum_abs_d": 0, "net": 0, "changed": 0})
        g["designs"].append(r)
        g["changed"] += bool(p) and p.get("d") != r["diff"]
        g["sum_abs_d"] += abs(r["diff"])
        g["net"] += r["diff"]
    return oob, groups, desc


