# ----------------------------------------------------------------------------- formatting

def fmt(x, digits=1):
    if x is None:
        return "–"
    if isinstance(x, float):
        return f"{x:,.{digits}f}"
    if isinstance(x, int):
        return f"{x:,}"
    return str(x)


def tex_escape(s):
    s = str(s)
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"), ("#", r"\#"),
                 ("_", r"\_"), ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"), ("^", r"\^{}"),
                 ("–", "--"), ("≤", r"$\le$"), ("→", r"$\to$"), ("Σ", r"$\Sigma$"), ("Δ", r"$\Delta$"),
                 ("−", r"$-$"), ("|", r"\textbar{}"), ("…", r"\ldots{}"), ("<", r"\textless{}"),
                 (">", r"\textgreater{}")):
        s = s.replace(a, b)
    return s


class Table:
    """A table written once as Markdown and once as a booktabs LaTeX tabular."""

    def __init__(self, name, caption, header, align, rows, source):
        self.name, self.caption, self.header, self.align, self.rows, self.source = \
            name, caption, header, align, rows, source

    def markdown(self):
        sep = ["---:" if a == "r" else "---" for a in self.align]
        lines = ["| " + " | ".join(self.header) + " |", "| " + " | ".join(sep) + " |"]
        lines += ["| " + " | ".join(str(c).replace("|", "\\|") for c in row) + " |" for row in self.rows]
        return "\n".join(lines)

    def latex(self):
        cols = "".join(self.align)  # a string of l/r/c or a list that may hold p{width} columns
        body = [" & ".join(tex_escape(c) for c in row) + r" \\" for row in self.rows]
        return "\n".join([
            f"% Generated by tools/hls-est-validate/thesis/make_thesis_tables.py; source: {tex_escape(self.source)}",
            r"\begin{table}[htbp]", r"\centering\small", f"\\caption{{{tex_escape(self.caption)}}}",
            f"\\label{{tab:{PREFIX}{self.name}}}", f"\\begin{{tabular}}{{{cols}}}", r"\toprule",
            " & ".join(tex_escape(h) for h in self.header) + r" \\", r"\midrule", *body,
            r"\bottomrule", r"\end{tabular}", r"\end{table}", ""])

    def write(self, out):
        d = out / "tables"
        d.mkdir(parents=True, exist_ok=True)
        (d / f"{PREFIX}{self.name}.md").write_text(
            f"<!-- Generated by tools/hls-est-validate/thesis/make_thesis_tables.py; source: {self.source}. "
            f"Do not edit. -->\n\n**{self.caption}**\n\n{self.markdown()}\n")
        (d / f"{PREFIX}{self.name}.tex").write_text(self.latex())


