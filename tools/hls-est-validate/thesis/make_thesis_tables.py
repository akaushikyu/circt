    statuses = [runs[r["key"]].get("status") or "" for r in in_run if r["cgeist_ok"] and not r["hlsest_ok"]]
    numbers["all_top_not_found"] = sum(st == "top not found" for st in statuses)
    numbers["all_hlsest_timeout"] = sum(st.startswith("hls-est timeout") for st in statuses)
    top_ab = max(ab, key=lambda a: a["d_exact"])
    numbers["ablation_top_pass"] = top_ab["pass"]
    numbers["ablation_top_lost"] = fmt(top_ab["d_exact"])
    by_pass = {a["pass"]: a for a in ab}
    numbers["ablation_apu_ratio"] = fmt(by_pass["auto-pipeline-unroll"]["abs_err_without"] / ab_ref["abs_err"], 1)
    numbers["ablation_sched_ratio"] = fmt(by_pass["convert-affine-to-loopschedule"]["abs_err_without"] / ab_ref["abs_err"], 1)
    numbers["datasets_n"] = len({r["dataset"] for r in rows if r["in_run"]})
    numbers["ablation_zero"] = sum(1 for a in ab if a["d_exact"] == 0 and a["abs_err_without"] == ab_ref["abs_err"])
    big = sorted(groups.items(), key=lambda kv: -kv[1]["sum_abs_d"])
