@lru_cache(maxsize=None)
def experiment(name):
    """The newest result.json of an ad-hoc kernel run (vitis_adhoc.py), with its path."""
    files = glob.glob(str(EXPERIMENTS / name / "*" / "result.json"))
    if not files:
        raise KeyError(f"no Vitis run of kernel '{name}' under {EXPERIMENTS}")
    f = max(files, key=os.path.getmtime)
    with open(f) as fh:
        d = json.load(fh)
    d["_path"] = f
    return d


def experiment_index(cutoff=None):
    """Every ad-hoc run: (name, status, date of its result file).  With cutoff (a datetime), only result
    files written up to it count, so that the chapter's counts are frozen at the thesis snapshot."""
    out = []
    for f in glob.glob(str(EXPERIMENTS / "*" / "*" / "result.json")):
        if cutoff is not None and datetime.datetime.fromtimestamp(os.path.getmtime(f)) > cutoff:
            continue
        try:
            with open(f) as fh:
                st = json.load(fh).get("status")
        except Exception:
            st = "unreadable"
        name = Path(f).parent.parent.name
        day = datetime.date.fromtimestamp(os.path.getmtime(f)).isoformat()
        out.append((name, st, day))
    return out


def mem_rows(d, limit=4):
    """Compact memory rows: array Words x Bits core = BRAM (banks summed per array and core)."""
    agg = {}
    for m in d.get("memories", []) or []:
        arr = m.get("array") or m.get("Memory")
        core = (m.get("core") or "").replace("_AUTO", "")
        key = (arr, core, m.get("Words"), m.get("Bits"))
        a = agg.setdefault(key, [0, 0])
        a[0] += 1
        a[1] += m.get("bram") or m.get("BRAM_18K") or 0
    parts = []
    for (arr, core, w, b), (n, br) in agg.items():
        banks = f"{n}x " if n > 1 else ""
        parts.append(f"{arr}: {banks}{w}x{b} {core} {br}")
    if len(parts) > limit:
        parts = parts[:limit] + [f"+{len(parts) - limit} more"]
    return "; ".join(parts)


def adapter_rows(d):
    return "; ".join(f"{i['Instance']} {i['BRAM_18K']}" for i in d.get("instances", []) or []
                     if i.get("BRAM_18K") and "m_axi" in i.get("Instance", ""))


def loop_rows(d, limit=3, only=None, lat=False):
    """Pipelined loops: name, trip count, achieved II (and the iteration latency when lat)."""
    parts = []
    for lp in d.get("loops", []) or []:
        if str(lp.get("pipelined")) != "yes":
            continue
        if only and not any(o in lp["name"] for o in only):
            continue
        s = f"{lp['name']} trip {lp.get('trip_count')} II {lp.get('ii_achieved')}"
        if lat:
            s += f" latency {lp.get('iter_latency')}"
        parts.append(s)
    if len(parts) > limit:
        parts = parts[:limit] + [f"+{len(parts) - limit} more"]
    return "; ".join(parts)


_OPERATOR_MODULE = re.compile(r"^(mul|mac|add|sub|ama|fadd|fmul|fsub|dadd|dmul|dsub|fdiv|ddiv|fsqrt|dsqrt|"
                              r"sitofp|uitofp|fptosi|fptoui|fpext|fptrunc|fcmp|dcmp|mux|sparsemux|urem|srem|"
                              r"udiv|sdiv|flow_control|fifo|regslice|.*_m_axi|.*_s_axi|.*_fifo_).*")


def instance_rows(d, limit=4):
    """Module instances that are user or library functions (not operators, adapters or FIFOs)."""
    names = [i["Module"] for i in d.get("instances", []) or []
             if not _OPERATOR_MODULE.match(i.get("Module", ""))]
    counts = {}
    for n in names:
        counts[n] = counts.get(n, 0) + 1
    parts = [f"{n} x{c}" if c > 1 else n for n, c in counts.items()]
    if len(parts) > limit:
        parts = parts[:limit] + [f"+{len(parts) - limit} more"]
    return "; ".join(parts)


def log_ids(d):
    log = d.get("log") or {}
    ids = [LOG_IDS[k] for k in LOG_IDS if log.get(k) and not (k == "error" and d.get("status") == "ok")]
    return ", ".join(ids)


def kernel_summary(name, opts=None):
    """What the kernel table of a rule shows, all read from the run's result.json. opts: loops (list of
    loop-name substrings), lat (show iteration latency), inst (show function instances), mems (list of
    array names to show)."""
    opts = opts or {}
    d = experiment(name)
    st = d.get("status")
    if st != "ok":
        note = (d.get("note") or "").replace("\n", " ")
        m = re.search(r"\[HLS [\d-]+\][^(]*", note)
        return {"status": st, "bram": "-", "detail": f"{st}: {m.group(0).strip() if m else note[:120]}",
                "loops": "", "logs": log_ids(d), "path": d["_path"]}
    if opts.get("mems"):
        keep = set(opts["mems"])
        dd = dict(d)
        dd["memories"] = [m for m in d.get("memories", []) or []
                          if (m.get("array") or m.get("Memory")) in keep]
        detail = mem_rows(dd)
    else:
        detail = mem_rows(d)
    ad = adapter_rows(d)
    if ad:
        detail = (detail + "; " if detail else "") + "adapter " + ad
    if opts.get("inst"):
        ins = instance_rows(d)
        detail = (detail + "; " if detail else "") + ("instances: " + ins if ins else "no function instance")
    return {"status": st, "bram": d.get("totals", {}).get("BRAM"), "detail": detail,
            "loops": loop_rows(d, only=opts.get("loops"), lat=opts.get("lat", False)),
            "logs": log_ids(d), "path": d["_path"]}


def kernel_value(spec):
    """Inline references in hand-written prose: [[name]] -> total BRAM; [[name:ii:LOOP]] -> achieved II
    of the first pipelined loop whose name contains LOOP; [[name:mem:ARRAY]] -> 'WxB core N' of the
    array; [[name:lat:LOOP]] -> iteration latency."""
    parts = spec.split(":")
    d = experiment(parts[0])
    if len(parts) == 1:
        if d.get("status") != "ok":
            return d.get("status")
        return str(d.get("totals", {}).get("BRAM"))
    kind, arg = parts[1], ":".join(parts[2:])
    if kind in ("ii", "lat"):
        for lp in d.get("loops", []) or []:
            if arg in lp["name"] and str(lp.get("pipelined")) == "yes":
                return str(lp.get("ii_achieved") if kind == "ii" else lp.get("iter_latency"))
        raise KeyError(f"{parts[0]}: no pipelined loop named like '{arg}'")
    if kind == "mem":
        dd = dict(d)
        dd["memories"] = [m for m in d.get("memories", []) or [] if (m.get("array") or m.get("Memory")) == arg]
        if not dd["memories"]:
            raise KeyError(f"{parts[0]}: no memory row of array '{arg}'")
        return mem_rows(dd).split(": ", 1)[1]
    raise KeyError(spec)


def expand_kernel_refs(text, used=None):
    def sub(m):
        if used is not None:
            used.add(m.group(1).split(":")[0])
        return kernel_value(m.group(1))
    return re.sub(r"\[\[([^\]]+)\]\]", sub, text)


