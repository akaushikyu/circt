def md_cell(x):
    s = "" if x is None else str(x)
    return s.replace("|", "\\|").replace("\n", " ")


def md_table(headers, rows, align=None):
    align = align or ["---"] * len(headers)
    out = ["| " + " | ".join(md_cell(h) for h in headers) + " |",
           "|" + "|".join(align) + "|"]
    for r in rows:
        out.append("| " + " | ".join(md_cell(c) for c in r) + " |")
    return "\n".join(out)


_TEX = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
        "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
        "<": r"\textless{}", ">": r"\textgreater{}", "|": r"\textbar{}"}


def tex_escape(x):
    s = "" if x is None else str(x)
    s = s.replace("`", "").replace("**", "")
    s = s.replace("≤", "<=").replace("≥", ">=").replace("→", "->").replace("×", "x").replace("Σ", "sum")
    return "".join(_TEX.get(c, c) for c in s)


def tex_table(headers, rows, caption, label, colspec=None, gen_line=""):
    colspec = colspec or "l" * len(headers)
    if len(rows) > 25:   # a long table breaks across pages (needs \usepackage{longtable})
        head = " & ".join(tex_escape(h) for h in headers) + r" \\"
        out = [f"% {gen_line}" if gen_line else "%", r"{\small",
               rf"\begin{{longtable}}{{{colspec}}}",
               rf"\caption{{{tex_escape(caption)}}}\label{{{label}}} \\", r"\toprule", head, r"\midrule",
               r"\endfirsthead", r"\toprule", head, r"\midrule", r"\endhead", r"\bottomrule", r"\endlastfoot"]
        for r in rows:
            out.append(" & ".join(tex_escape(c) for c in r) + r" \\")
        out += [r"\end{longtable}", "}", ""]
        return "\n".join(out)
    out = [f"% {gen_line}" if gen_line else "%",
           r"\begin{table}[htbp]", r"\centering", r"\small",
           rf"\caption{{{tex_escape(caption)}}}", rf"\label{{{label}}}",
           rf"\begin{{tabular}}{{{colspec}}}", r"\toprule",
           " & ".join(tex_escape(h) for h in headers) + r" \\", r"\midrule"]
    for r in rows:
        out.append(" & ".join(tex_escape(c) for c in r) + r" \\")
    out += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    return "\n".join(out)


def write_table(basename, headers, rows, caption, label, gen_line, colspec=None, md_align=None):
    """Write tables/<basename>.md and .tex; return the Markdown table."""
    TABLES.mkdir(parents=True, exist_ok=True)
    md = md_table(headers, rows, md_align)
    with open(TABLES / f"{basename}.md", "w") as fh:
        fh.write(f"<!-- {gen_line} -->\n\n**{caption}**\n\n{md}\n")
    with open(TABLES / f"{basename}.tex", "w") as fh:
        fh.write(tex_table(headers, rows, caption, label, colspec, gen_line))
    return md


def fill_template(text, values):
    """Replace {{name}} placeholders; every placeholder must be known and every value used."""
    used = set()

    def sub(m):
        k = m.group(1)
        if k not in values:
            raise KeyError(f"template placeholder '{k}' has no value")
        used.add(k)
        return str(values[k])
    out = re.sub(r"\{\{([A-Za-z0-9_]+)\}\}", sub, text)
    unused = set(values) - used
    if unused:
        raise KeyError(f"values not used by the template: {sorted(unused)}")
    return out


def config_keys():
    """Every leaf key path of the default configuration dump checked into the lit inputs."""
    with open(REPO / "test/hls-est/Config/Inputs/default-config.json") as fh:
        d = json.load(fh)
    keys = set()

    def walk(x, p):
        if isinstance(x, dict):
            for k, v in x.items():
                walk(v, f"{p}.{k}" if p else k)
        else:
            keys.add(p)
    walk(d, "")
    return keys


def check_config_key(key, keys):
    """True when key (or a prefix of a listed key) exists in the default configuration."""
    k = key.split("[")[0]
    return any(x == k or x.startswith(k + ".") for x in keys)


