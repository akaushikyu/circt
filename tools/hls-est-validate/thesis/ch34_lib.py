def read_text(p):
    """A file's text; the notes files are read at the thesis snapshot commit (thesis_data.notes_text)."""
    if Path(p).parent == NOTES:
        import thesis_data as T
        return T.notes_text(Path(p).name)
    with open(p, encoding="utf-8") as fh:
        return fh.read()


def vitis_note_headings():
    """[(id, title, status)] of VITIS_NOTES.md, status from the shared parser thesis_data.note_status."""
    import thesis_data as T
    return [(i, v["title"], v["status"]) for i, v in T.vitis_notes_index().items()]


def note_title(nid):
    for i, t, _ in vitis_note_headings():
        if i == nid:
            return t
    raise KeyError(nid)


def changelog_entries():
    """[(heading, body)] of CHANGELOG.md, newest first."""
    text = read_text(NOTES / "CHANGELOG.md")
    parts = re.split(r"^## ", text, flags=re.M)[1:]
    out = []
    for p in parts:
        head, _, body = p.partition("\n")
        out.append((head.strip(), body))
    return out


def changelog_effect(heading_substr, find=None, limit=420):
    """A verbatim excerpt of the Effect bullet of the CHANGELOG entry whose heading contains
    heading_substr: the sentence containing `find`, else the bullet's first sentence."""
    for head, body in changelog_entries():
        if heading_substr not in head:
            continue
        lines = body.splitlines()
        start = next((i for i, ln in enumerate(lines) if ln.startswith("- **Effect")), None)
        if start is None:
            raise KeyError(f"CHANGELOG entry '{head}' has no Effect bullet")
        chunk = [re.sub(r"^- \*\*Effect[^*]*\*\*:?\s*", "", lines[start])]
        for ln in lines[start + 1:]:
            if ln.startswith("- **"):
                break
            chunk.append(re.sub(r"^\s*- ", "", ln))
        text = " ".join(x.strip() for x in chunk if x.strip())
        if find:
            src = text if find in text else body
            i = src.find(find)
            if i < 0:
                raise KeyError(f"'{find}' not in the CHANGELOG entry '{head}'")
            rest = src[i:].split("\n")[0]
            m2 = re.search(r"(?<=[.])\s+(?=[A-Z(*`])", rest)
            pick = rest[:m2.start()] if m2 else rest
        else:
            pick = re.split(r"(?<=[.;])\s+(?=[A-Z(*`])", text)[0]
        pick = pick.strip()
        if len(pick) > limit:
            cut = pick[:limit]
            cut = cut[:cut.rfind(" ")] if " " in cut else cut
            pick = cut + " ..."
        return head, pick
    raise KeyError(f"no CHANGELOG entry with '{heading_substr}' in its heading")


